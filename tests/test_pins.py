"""The app runs on requirements.txt and the tests run on requirements-dev.txt, so every runtime pin must be tested at
the same version. Both lists are compiled from the .in files with a cutoff two weeks back (README, Updating the Python
pins)."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def pins(name: str) -> dict[str, str]:
    lines = (ROOT / name).read_text().splitlines()
    return {
        line.split("==")[0].strip().lower(): line.split("==")[1].split(";")[0].strip()
        for line in lines
        if "==" in line and not line.lstrip().startswith("#")
    }


def test_every_runtime_pin_is_tested_at_the_same_version() -> None:
    runtime, dev = pins("requirements.txt"), pins("requirements-dev.txt")
    assert runtime, "no pins read from requirements.txt"
    differ = {name: (version, dev.get(name)) for name, version in runtime.items() if dev.get(name) != version}
    assert differ == {}


def test_the_lists_are_compiled_with_a_cutoff() -> None:
    """Each list names the uv command that made it, with its --exclude-newer cutoff: a list typed by hand would not."""
    for name in ("requirements.txt", "requirements-dev.txt"):
        header = (ROOT / name).read_text().splitlines()[:2]
        assert header[0] == "# This file was autogenerated by uv via the following command:", (name, header)
        assert "--exclude-newer" in header[1], (name, header)


def test_each_pin_an_in_file_names_is_compiled_at_that_version() -> None:
    """A pin bumped by hand in a compiled list, and not in its .in file, skips the cutoff; the next compile undoes
    it."""
    for source, compiled in (("requirements.in", "requirements.txt"), ("requirements-dev.in", "requirements-dev.txt")):
        named, built = pins(source), pins(compiled)
        assert named, f"no pins read from {source}"
        differ = {name: (version, built.get(name)) for name, version in named.items() if built.get(name) != version}
        assert differ == {}, (source, compiled)
